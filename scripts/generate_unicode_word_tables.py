"""Regenerate native Python 3.11/3.12 regex word tables from pinned UCD files.

Inputs: ICU release-70-1 and release-72-1, respectively Unicode 14.0/15.0,
icu4c/source/data/unidata/UnicodeData.txt. Verify SHA-256 before generating.
"""
import argparse
import hashlib
from pathlib import Path

HASHES = {
    '14': '36018e68657fdcb3485f636630ffe8c8532e01c977703d2803f5b89d6c5feafb',
    '15': '806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73',
}


def points(path, version):
    data = Path(path).read_bytes()
    if hashlib.sha256(data).hexdigest() != HASHES[version]:
        raise ValueError('UnicodeData hash does not match pinned '+version)
    result = set(); first = None
    for line in data.decode('utf-8').splitlines():
        fields = line.split(';'); point = int(fields[0], 16); name = fields[1]; category = fields[2]
        if name.endswith(', First>'):
            first = (point, category)
        elif name.endswith(', Last>'):
            if first is None or first[1] != category:
                raise ValueError('invalid UCD range')
            if category[0] in 'LN': result.update(range(first[0], point+1))
            first = None
        elif category[0] in 'LN': result.add(point)
    if first is not None: raise ValueError('unterminated UCD range')
    return result


def ranges(values):
    values = sorted(values)
    if not values: return []
    start = end = values[0]; result = []
    for point in values[1:]:
        if point == end+1: end = point
        else: result.append((start, end)); start = end = point
    result.append((start, end))
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--ucd14', required=True); parser.add_argument('--ucd15', required=True)
    parser.add_argument('--out', required=True)
    args = parser.parse_args()
    old = points(args.ucd14, '14'); new = points(args.ucd15, '15')
    if old-new: raise ValueError('Unicode 15 removed alphanumeric code points; regenerate format')
    output = ['//! Generated by scripts/generate_unicode_word_tables.py from pinned UnicodeData.',
              '//! Unicode 14.0 and 15.0; Unicode data copyright Unicode, Inc.', '']
    for name, values in [('WORD_14', old), ('WORD_15_ADDITIONS', new-old)]:
        output.append('pub(crate) static '+name+': &[(u32, u32)] = &[')
        output.extend(f'    (0x{a:X}, 0x{b:X}),' for a,b in ranges(values))
        output.extend(['];', ''])
    Path(args.out).write_text('\n'.join(output), encoding='utf-8')


if __name__ == '__main__': main()
